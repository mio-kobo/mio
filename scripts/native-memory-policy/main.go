// Regenerate the pure Mio native policy emitter from the shared symbolic ARM64
// template. Native self-compilation uses only the resulting Mio source.
package main

import (
	"Mio/internal/aot/darwinarm64"
	"encoding/json"
	"fmt"
	"os"
	"sort"
	"strings"
)

func main() {
	p := darwinarm64.M19cPolicyTemplate()
	if len(os.Args) > 1 && os.Args[1] == "--json" {
		json.NewEncoder(os.Stdout).Encode(p)
		return
	}
	labels := map[int][]string{}
	for name, at := range p.Labels {
		labels[at] = append(labels[at], name)
	}
	rel := map[int]darwinarm64.M19cPolicyRelocation{}
	for _, r := range p.Relocations {
		rel[r.At] = r
	}
	var s strings.Builder
	s.WriteString("// Code generated by go run ./scripts/native-memory-policy; DO NOT EDIT.\n// Shared native memory policy. Pure Mio performs every branch relocation.\n// Word constants encode ordinary ARM64 instructions, not a runtime Go dependency.\nwaza emit_memory_policy(code: arm64.Assembler) -> unit {\n")
	for i, w := range p.Words {
		names := labels[i]
		sort.Strings(names)
		for _, n := range names {
			fmt.Fprintf(&s, " arm64.assembler_label(code, %q);\n", n)
		}
		r, ok := rel[i]
		if !ok {
			fmt.Fprintf(&s, " observation_word(code, %d);\n", w)
			continue
		}
		switch r.Kind {
		case 0:
			fmt.Fprintf(&s, " arm64.assembler_b(code, %q);\n", r.Label)
		case 1:
			fmt.Fprintf(&s, " arm64.assembler_bl(code, %q);\n", r.Label)
		case 2:
			fmt.Fprintf(&s, " arm64.assembler_b_cond(code, %d, %q);\n", r.Cond, r.Label)
		case 3:
			fmt.Fprintf(&s, " arm64.assembler_cbz_x(code, %d, %q);\n", r.Reg, r.Label)
		case 4:
			fmt.Fprintf(&s, " arm64.assembler_cbnz_x(code, %d, %q);\n", r.Reg, r.Label)
		}
	}
	s.WriteString("}\n")
	path := "bunko/kiso/aot/lower/memory_policy.mio"
	if len(os.Args) > 1 && os.Args[1] == "--check" {
		old, e := os.ReadFile(path)
		if e != nil || string(old) != s.String() {
			fmt.Fprintln(os.Stderr, "generated memory policy is stale")
			os.Exit(1)
		}
		return
	}
	if err := os.WriteFile(path, []byte(s.String()), 0644); err != nil {
		panic(err)
	}
}
