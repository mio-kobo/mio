#!/usr/bin/env python3
"""Generate native scaffold assets from the same JSON embedded by Go (development only)."""
import argparse
import json
from pathlib import Path
ROOT = Path(__file__).resolve().parents[2]
SOURCE = ROOT / 'internal/bunkoscaffold/templates.json'
OUTPUT = ROOT / 'selfhost/bunkoscaffold/templates_generated.mio'
def render():
    data = json.loads(SOURCE.read_text())
    lines = ['// Generated by scripts/bunko/generate.py; do not edit.']
    for key, value in data.items():
        if isinstance(value, str):
            lines.append('waza asset_%s() -> string { kaesu %s; }' % (key, json.dumps(value, ensure_ascii=False)))
        else:
            lines.append('koukai waza policy_targets() -> []string { kaesu %s; }' % json.dumps(value))
    return '\n'.join(lines)+'\n'
def main():
    p=argparse.ArgumentParser();p.add_argument('--check',action='store_true');args=p.parse_args();out=render()
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text()!=out:raise SystemExit('native Bunko scaffold assets are stale')
    else:OUTPUT.write_text(out)
if __name__=='__main__':main()
