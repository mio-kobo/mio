package darwinarm64

const (
	m11ObjectMarkEntry    = "m11.object.mark"
	m11ObjectCollectEntry = "m11.object.collect"
	m11AutoAllocEntry     = "m11.object.alloc"
	m11TryMarkEntry       = "m11.object.trymark"
	M11MaxShadowFrames    = 1024
	M11MaxRootsPerFrame   = MaxM4Locals + MaxM5OperandSlots + MaxGlobalSlots
)

func m11Lsrv(rd, rn, rm uint32) uint32 { return 0x9AC02400 | rm<<16 | rn<<5 | rd }

func appendM11ObjectRuntime(b *m8Assembler, stress bool) {
	appendM11AutoAlloc(b, stress)
	appendM11ObjectCollect(b)
	appendM11ObjectMark(b)
}

// auto_alloc(heap,type,payload) first tries the M10 free-list allocator. A
// failed request runs a precise collection over x24's shadow-frame chain and
// retries once. Stress mode collects before the first attempt.
func appendM11AutoAlloc(b *m8Assembler, stress bool) {
	b.label(m11AutoAllocEntry)
	b.emit(subImmX(31, 31, 32), strX(30, 31, 0), strX(0, 31, 1), strX(1, 31, 2), strX(2, 31, 3))
	if stress {
		b.emit(ldrX(0, 31, 1), movX(1, 24))
		b.bl(m11ObjectCollectEntry)
		b.emit(m8Movn(9, 0), m8Cmp(0, 9))
		b.bc(0, "m11.auto.fail")
	}
	b.emit(ldrX(0, 31, 1), ldrX(1, 31, 2), ldrX(2, 31, 3))
	b.bl(m10AllocEntry)
	b.cbnz(0, "m11.auto.done")
	if !stress {
		b.emit(ldrX(0, 31, 1), movX(1, 24))
		b.bl(m11ObjectCollectEntry)
		b.emit(m8Movn(9, 0), m8Cmp(0, 9))
		b.bc(0, "m11.auto.fail")
		b.emit(ldrX(0, 31, 1), ldrX(1, 31, 2), ldrX(2, 31, 3))
		b.bl(m10AllocEntry)
	}
	b.cbnz(0, "m11.auto.done")
	// Preserve the physical request that actually exhausted both bump and free
	// allocation paths. This is available even when the payload is only zero.
	b.emit(ldrX(9, 31, 3), addImmX(9, 9, 31), m8Movn(10, 15), m8And(9, 9, 10), ldrX(10, 31, 1), ldrX(10, 10, 2), strX(9, 10, m8TelOOMRequestBytes))
	b.b("m11.auto.done")
	b.label("m11.auto.fail")
	b.emit(movzX(0, 0))
	b.label("m11.auto.done")
	b.emit(ldrX(30, 31, 0), addImmX(31, 31, 32), m8Ret())
}

func appendM11ObjectCollect(b *m8Assembler) {
	b.label(m11ObjectCollectEntry)
	b.emit(subImmX(31, 31, 32), strX(30, 31, 0), strX(0, 31, 1), strX(1, 31, 2))
	b.emit(mrsCNTVCT(9), strX(9, 31, 3))
	b.bl(m11ObjectMarkEntry)
	b.emit(m8Movn(9, 0), m8Cmp(0, 9))
	b.bc(0, "m11.collect.done")
	b.emit(ldrX(0, 31, 1), movzX(1, 0), movzX(2, 0))
	b.bl(m10SweepEntry)
	b.label("m11.collect.done")
	// Record time without allocating or calling into managed code. CNTVCT is a
	// monotonic user-accessible ARM64 counter; the matching frequency is stored
	// so diagnostics can report an exact duration.
	b.emit(movX(10, 0), mrsCNTVCT(9), ldrX(11, 31, 3), m10Sub(9, 9, 11), ldrX(11, 31, 1), ldrX(12, 11, 2))
	b.emit(ldrX(13, 12, m8TelGCCount), addImmX(13, 13, 1), strX(13, 12, m8TelGCCount))
	b.emit(strX(9, 12, m8TelLastGCTicks), ldrX(13, 12, m8TelTotalGCTicks), addX(13, 13, 9), strX(13, 12, m8TelTotalGCTicks))
	b.emit(mrsCNTFRQ(13), strX(13, 12, m8TelTimerFrequency), movX(0, 10))
	b.emit(ldrX(30, 31, 0), addImmX(31, 31, 32), m8Ret())
}

func appendM11ObjectMark(b *m8Assembler) {
	b.label(m11ObjectMarkEntry)
	m10SaveCallee(b)
	b.emit(movX(19, 0), movX(20, 1), movzX(23, 0))
	b.cbz(19, "m11.mark.fail")
	b.emit(ldrX(9, 19, 0))
	b.emit(m8MovBits(10, m8HeapMagic)...)
	b.emit(m8Cmp(9, 10))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(21, 19, 6), ldrX(22, 19, 1), m8Cmp(21, 22))
	b.bc(8, "m11.mark.fail")
	b.emit(ldrX(9, 19, 2), m8Cmp(22, 9))
	b.bc(8, "m11.mark.fail")

	// Clear old mark state while validating every physical span.
	b.emit(movX(25, 21))
	b.label("m11.clear.loop")
	b.emit(m8Cmp(25, 22))
	b.bc(0, "m11.roots.begin")
	b.bc(8, "m11.mark.fail")
	b.emit(ldrX(9, 25, 1))
	b.emit(m8MovBits(10, M8MaxHeapCapacity)...)
	b.emit(m8Cmp(9, 10))
	b.bc(8, "m11.mark.fail")
	b.emit(addImmX(10, 9, 31), m8Movn(11, 15), m8And(10, 10, 11), addX(11, 25, 10), m8Cmp(11, 22))
	b.bc(8, "m11.mark.fail")
	b.emit(m9LdrW(9, 25, 0), m9LdrW(12, 25, 4))
	b.cbz(9, "m11.clear.free")
	b.emit(movzW(12, 0), m9StrW(12, 25, 4))
	b.b("m11.clear.next")
	b.label("m11.clear.free")
	b.emit(movzX(13, 7), m8And(13, 12, 13), cmpImmX(13, M10FreeBit))
	b.bc(1, "m11.mark.fail")
	b.label("m11.clear.next")
	b.emit(movX(25, 11))
	b.b("m11.clear.loop")

	// Walk exact shadow roots. record = {previous,count,values...}.
	b.label("m11.roots.begin")
	b.emit(movX(25, 20), movzX(27, 0))
	b.label("m11.roots.frame")
	b.cbz(25, "m11.scan.begin")
	b.emit(addImmX(27, 27, 1), cmpImmX(27, M11MaxShadowFrames))
	b.bc(8, "m11.mark.fail")
	b.emit(ldrX(26, 25, 1))
	b.emit(m8MovBits(9, uint64(M11MaxRootsPerFrame))...)
	b.emit(m8Cmp(26, 9))
	b.bc(8, "m11.mark.fail")
	b.emit(movzX(28, 0))
	b.label("m11.roots.value")
	b.emit(m8Cmp(28, 26))
	b.bc(2, "m11.roots.next")
	b.emit(m10Lsl(9, 28, 3), addImmX(9, 9, 16), addX(9, 25, 9), ldrX(0, 9, 0))
	b.bl(m11TryMarkEntry)
	b.emit(addImmX(28, 28, 1))
	b.b("m11.roots.value")
	b.label("m11.roots.next")
	b.emit(ldrX(25, 25, 0))
	b.b("m11.roots.frame")

	// Fixed-point scan. Dynamic M12 layouts carry their exact reference bitmap.
	b.label("m11.scan.begin")
	b.emit(strX(23, 31, 11), movX(25, 21))
	b.label("m11.scan.loop")
	b.emit(m8Cmp(25, 22))
	b.bc(2, "m11.scan.end")
	b.emit(m9LdrW(9, 25, 4), cmpImmX(9, M9MarkBit))
	b.bc(1, "m11.scan.next")
	b.emit(movzW(9, M9MarkBit|M9ScannedBit), m9StrW(9, 25, 4), m9LdrW(10, 25, 0), addImmX(17, 25, M8ObjectHeaderSize), ldrX(15, 25, 1))
	b.emit(cmpImmX(10, M12StructTypeID))
	b.bc(0, "m11.scan.struct")
	b.emit(cmpImmX(10, M12ArrayTypeID))
	b.bc(0, "m11.scan.array")
	b.emit(cmpImmX(10, M12StorageTypeID))
	b.bc(0, "m11.scan.storage")
	b.emit(cmpImmX(10, M15ClosureTypeID))
	b.bc(0, "m11.scan.closure")
	b.emit(cmpImmX(10, M15EnvironmentTypeID))
	b.bc(0, "m11.scan.environment")
	b.emit(cmpImmX(10, M15CellTypeID))
	b.bc(0, "m11.scan.cell")
	b.emit(cmpImmX(10, M13NullableTypeID))
	b.bc(0, "m11.scan.nullable")
	b.emit(cmpImmX(10, M13EnumTypeID))
	b.bc(0, "m11.scan.enum")
	b.b("m11.mark.fail")

	b.label("m11.scan.struct")
	b.emit(cmpImmX(15, m12PayloadBase))
	b.bc(3, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), cmpImmX(9, m12StructKind))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(26, 17, 1), ldrX(27, 17, 3))
	b.emit(ldrX(9, 17, 2), m8Cmp(26, 9))
	b.bc(1, "m11.mark.fail")
	b.emit(m8MovBits(9, uint64(M8MaxHeapCapacity/8))...)
	b.emit(m8Cmp(26, 9))
	b.bc(8, "m11.mark.fail")
	// bitmapWords == ceil(fieldCount/64)
	b.emit(addImmX(9, 26, 63), m10Lsr(9, 9, 6), m8Cmp(9, 27))
	b.bc(1, "m11.mark.fail")
	// required = 32 + bitmapWords*8 + fieldCount*8 <= payload.
	b.emit(addX(10, 27, 26), m10Lsl(10, 10, 3), addImmX(10, 10, m12PayloadBase), m8Cmp(10, 15))
	b.bc(8, "m11.mark.fail")
	b.emit(m10Lsl(9, 27, 3), addImmX(12, 17, m12PayloadBase), addX(14, 12, 9), movzX(28, 0))
	b.label("m11.struct.field")
	b.emit(m8Cmp(28, 26))
	b.bc(2, "m11.scan.restart")
	b.emit(m10Lsr(9, 28, 6), m10Lsl(9, 9, 3), addX(9, 12, 9), ldrX(10, 9, 0), movzX(11, 63), m8And(11, 28, 11), m11Lsrv(10, 10, 11), movzX(11, 1), m8And(10, 10, 11))
	b.cbz(10, "m11.struct.next")
	b.emit(m10Lsl(9, 28, 3), addX(9, 14, 9), ldrX(0, 9, 0))
	b.bl(m11TryMarkEntry)
	b.label("m11.struct.next")
	// trymark uses x9-x12; rebuild the bitmap base before the next field.
	b.emit(addImmX(12, 17, m12PayloadBase), addImmX(28, 28, 1))
	b.b("m11.struct.field")

	b.label("m11.scan.array")
	b.emit(cmpImmX(15, 48))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), movzX(10, 255), m8And(9, 9, 10), cmpImmX(9, m12ArrayKind))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 3), cmpImmX(9, 1))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 4), cmpImmX(9, 1))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 1), ldrX(10, 17, 2), m8Cmp(9, 10))
	b.bc(8, "m11.mark.fail")
	b.emit(ldrX(0, 17, 5))
	b.bl(m11TryMarkEntry)
	b.b("m11.scan.restart")

	b.label("m11.scan.storage")
	b.emit(cmpImmX(15, m12PayloadBase))
	b.bc(3, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), movzX(10, 255), m8And(10, 9, 10), cmpImmX(10, m12StorageKind))
	b.bc(1, "m11.mark.fail")
	b.emit(m10Lsr(10, 9, 8), movzX(11, 255), m8And(10, 10, 11))
	b.emit(cmpImmX(10, 1))
	b.bc(0, "m11.storage.width.ok")
	b.emit(cmpImmX(10, 8))
	b.bc(1, "m11.mark.fail")
	b.label("m11.storage.width.ok")
	b.emit(ldrX(26, 17, 1), ldrX(11, 17, 2), cmpImmX(11, 1))
	b.bc(1, "m11.mark.fail")
	b.emit(subImmX(12, 15, m12PayloadBase), udivX(13, 12, 10), m8Cmp(26, 13))
	b.bc(8, "m11.mark.fail")
	b.emit(mulX(12, 26, 10), addImmX(12, 12, m12PayloadBase), m8Cmp(12, 15))
	b.bc(1, "m11.mark.fail")
	b.emit(m10Lsr(9, 9, 16), movzX(11, 1), m8And(9, 9, 11), ldrX(11, 17, 3), m8Cmp(9, 11))
	b.bc(1, "m11.mark.fail")
	b.cbz(9, "m11.scan.restart")
	b.emit(cmpImmX(10, 8))
	b.bc(1, "m11.mark.fail")
	b.emit(addImmX(27, 17, m12PayloadBase), movzX(28, 0))
	b.label("m11.storage.ref")
	b.emit(m8Cmp(28, 26))
	b.bc(2, "m11.scan.restart")
	b.emit(m10Lsl(9, 28, 3), addX(9, 27, 9), ldrX(0, 9, 0))
	b.bl(m11TryMarkEntry)
	b.emit(addImmX(28, 28, 1))
	b.b("m11.storage.ref")

	b.label("m11.scan.closure")
	b.emit(cmpImmX(15, m15ClosurePayload))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), cmpImmX(9, m15ClosureKind))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 3), cmpImmX(9, 1))
	b.bc(8, "m11.mark.fail")
	b.emit(ldrX(0, 17, 5))
	b.bl(m11TryMarkEntry)
	b.b("m11.scan.restart")

	b.label("m11.scan.environment")
	b.emit(cmpImmX(15, 16))
	b.bc(3, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), cmpImmX(9, m15EnvironmentKind))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(26, 17, 1), m10Lsl(9, 26, 3), addImmX(9, 9, 16), m8Cmp(9, 15))
	b.bc(1, "m11.mark.fail")
	b.emit(movzX(28, 0))
	b.label("m11.environment.cell")
	b.emit(m8Cmp(28, 26))
	b.bc(2, "m11.scan.restart")
	b.emit(m10Lsl(9, 28, 3), addImmX(9, 9, 16), addX(9, 17, 9), ldrX(0, 9, 0))
	b.bl(m11TryMarkEntry)
	b.emit(addImmX(28, 28, 1))
	b.b("m11.environment.cell")

	b.label("m11.scan.cell")
	b.emit(cmpImmX(15, 16))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), movzX(10, 255), m8And(10, 9, 10), cmpImmX(10, m15CellKind))
	b.bc(1, "m11.mark.fail")
	b.emit(m10Lsr(9, 9, 8), movzX(10, 1), m8And(9, 9, 10))
	b.cbz(9, "m11.scan.restart")
	b.emit(ldrX(0, 17, 1))
	b.bl(m11TryMarkEntry)
	b.b("m11.scan.restart")

	b.label("m11.scan.nullable")
	b.emit(cmpImmX(15, 16))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), cmpImmX(9, m13NullableKind))
	b.bc(1, "m11.mark.fail")
	b.b("m11.scan.restart")

	b.label("m11.scan.enum")
	b.emit(cmpImmX(15, m12PayloadBase))
	b.bc(3, "m11.mark.fail")
	b.emit(ldrX(9, 17, 0), cmpImmX(9, m13EnumKind))
	b.bc(1, "m11.mark.fail")
	b.emit(ldrX(26, 17, 2), ldrX(27, 17, 3))
	b.emit(m8MovBits(9, uint64(M8MaxHeapCapacity/8))...)
	b.emit(m8Cmp(26, 9))
	b.bc(8, "m11.mark.fail")
	// bitmapWords == ceil(payloadCount/64).
	b.emit(addImmX(9, 26, 63), m10Lsr(9, 9, 6), m8Cmp(9, 27))
	b.bc(1, "m11.mark.fail")
	// required = 32 + bitmapWords*8 + payloadCount*8 <= payload.
	b.emit(addX(10, 27, 26), m10Lsl(10, 10, 3), addImmX(10, 10, m12PayloadBase), m8Cmp(10, 15))
	b.bc(8, "m11.mark.fail")
	b.emit(m10Lsl(9, 27, 3), addImmX(12, 17, m12PayloadBase), addX(14, 12, 9), movzX(28, 0))
	b.label("m11.enum.value")
	b.emit(m8Cmp(28, 26))
	b.bc(2, "m11.scan.restart")
	b.emit(m10Lsr(9, 28, 6), m10Lsl(9, 9, 3), addX(9, 12, 9), ldrX(10, 9, 0), movzX(11, 63), m8And(11, 28, 11), m11Lsrv(10, 10, 11), movzX(11, 1), m8And(10, 10, 11))
	b.cbz(10, "m11.enum.next")
	b.emit(m10Lsl(9, 28, 3), addX(9, 14, 9), ldrX(0, 9, 0))
	b.bl(m11TryMarkEntry)
	b.label("m11.enum.next")
	// trymark uses x9-x12; rebuild the bitmap base before the next payload.
	b.emit(addImmX(12, 17, m12PayloadBase), addImmX(28, 28, 1))
	b.b("m11.enum.value")

	b.label("m11.scan.restart")
	b.b("m11.scan.next")
	b.label("m11.scan.next")
	b.emit(ldrX(9, 25, 1), addImmX(9, 9, 31), m8Movn(10, 15), m8And(9, 9, 10), addX(25, 25, 9))
	b.b("m11.scan.loop")
	b.label("m11.scan.end")
	b.emit(ldrX(9, 31, 11), m8Cmp(9, 23))
	b.bc(1, "m11.scan.begin")
	b.label("m11.mark.success")
	b.emit(movX(0, 23))
	b.b("m11.mark.restore")
	b.label("m11.mark.fail")
	b.emit(m8Movn(0, 0))
	b.label("m11.mark.restore")
	m10RestoreCallee(b)

	// Candidate pointers are accepted only when they equal an allocated payload
	// start. Interior pointers, integers and stale free-block addresses are ignored.
	b.label(m11TryMarkEntry)
	b.cbz(0, "m11.try.done")
	// Reject tagged static strings, scalar-looking values and stale pointers in
	// O(1) before the exact-start scan. Without this guard every small tagged
	// string root would walk the entire multi-million-object heap.
	b.emit(addImmX(10, 21, M8ObjectHeaderSize), m8Cmp(0, 10))
	b.bc(3, "m11.try.done") // LO
	b.emit(m8Cmp(0, 22))
	b.bc(2, "m11.try.done") // HS
	// Precise root maps only contain object references. Validate their canonical
	// payload alignment and complete header/span in O(1); free blocks have type 0.
	b.emit(subImmX(9, 0, M8ObjectHeaderSize), m10Sub(10, 9, 21), movzX(11, 15), m8And(10, 10, 11), cmpZeroX(10))
	b.bc(1, "m11.try.done")
	b.emit(m9LdrW(10, 9, 0))
	b.cbz(10, "m11.try.done")
	b.emit(ldrX(11, 9, 1))
	b.emit(m8MovBits(12, M8MaxHeapCapacity)...)
	b.emit(m8Cmp(11, 12))
	b.bc(8, "m11.try.done")
	b.emit(addImmX(11, 11, 31), m8Movn(12, 15), m8And(11, 11, 12), addX(11, 9, 11), m8Cmp(11, 22))
	b.bc(8, "m11.try.done")
	b.emit(m9LdrW(10, 9, 4))
	b.cbnz(10, "m11.try.done")
	b.emit(movzW(10, M9MarkBit), m9StrW(10, 9, 4), addImmX(23, 23, 1))
	b.label("m11.try.done")
	b.emit(m8Ret())
}
